// Update artwork metadata from the actual card profession, including tokens.
import { readFile, writeFile, readdir } from 'node:fs/promises';
const palettes = JSON.parse(await readFile(new URL('../../Content/Source/Art/profession-palettes.json', import.meta.url), 'utf8'));
const recipePath = new URL('../../Content/Source/Art/emoji-recipes.json', import.meta.url);
const recipes = JSON.parse(await readFile(recipePath, 'utf8'));
let updated = 0, count = 0;
async function visit(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = new URL(entry.name + (entry.isDirectory() ? '/' : ''), directory);
    if (entry.isDirectory()) { await visit(path); continue; }
    if (!entry.name.endsWith('.json')) continue;
    const card = JSON.parse(await readFile(path, 'utf8')), recipe = recipes[card.id], palette = palettes[card.profession];
    if (!recipe || !palette) throw new Error(`Missing artwork or profession palette: ${card.id}`);
    if (recipe.top !== palette.top || recipe.bottom !== palette.bottom) updated++;
    recipe.profession = card.profession; recipe.top = palette.top; recipe.bottom = palette.bottom;
    count++;
  }
}
await visit(new URL('../../Content/Source/Cards/', import.meta.url));
await writeFile(recipePath, JSON.stringify(recipes, null, 2) + '\n');
await writeFile(new URL('profession-palettes.js', import.meta.url),
  '// Generated by sync-profession-colors.mjs from Content/Source/Art/profession-palettes.json.\n' +
  `globalThis.professionPalettes = ${JSON.stringify(palettes)};\n`);
console.log(`Synchronized ${count} card professions; corrected ${updated} background palettes.`);

// Rebuild the file://-friendly image bundle without accessing the network.
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { parseArgs } from 'node:util';
import './fusion-storage.js';
const { values } = parseArgs({ options: { 'shared-dir': { type: 'string' }, output: { type: 'string' } } });
const recipes = JSON.parse(await readFile(new URL('../../Content/Source/Art/emoji-recipes.json', import.meta.url), 'utf8'));
const entries = {};
for (const [id, recipe] of Object.entries(recipes).sort(([a], [b]) => a.localeCompare(b))) {
  if (!recipe.fusion) continue;
  if (recipe.fusion !== `Fusions/${id}.png`) throw new Error(`Unexpected fusion path: ${id}`);
  if (entries[recipe.fusionSource]) continue;
  const png = await readFile(new URL(`../../Content/Source/Art/${recipe.fusion}`, import.meta.url));
  entries[recipe.fusionSource] = { emoji: recipe.emoji, dataUrl: `data:image/png;base64,${png.toString('base64')}` };
}
const sharedDirectory = values['shared-dir'] ? resolve(values['shared-dir']) : new URL('shared-cache/', import.meta.url);
for (const name of (await readdir(sharedDirectory)).filter(name => name.endsWith('.json')).sort()) {
  const location = sharedDirectory instanceof URL ? new URL(name, sharedDirectory) : resolve(sharedDirectory, name);
  const bundle = JSON.parse(await readFile(location, 'utf8'));
  for (const item of globalThis.fusionStorage.validate(bundle)) {
    // Preserve the exact version of artwork already pinned by the card recipes.
    if (!entries[item.source]) entries[item.source] = { emoji: item.emoji, dataUrl: item.dataUrl };
  }
}
await writeFile(values.output ? resolve(values.output) : new URL('fusion-cache.js', import.meta.url),
  '// Generated by build-fusion-cache.mjs from Content/Source/Art and shared-cache. Do not edit.\n' +
  `globalThis.emojiFusionCache = ${JSON.stringify(entries)};\n`);
console.log(`Bundled ${Object.keys(entries).length} cached fusion images for offline use.`);
